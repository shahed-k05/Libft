#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int	i;
	int	j;
	int	sign;

	sign = 1;
	j = 0;
	i = 0;
	while (nptr[i] == ' ' || (nptr[i] >= 9 && nptr[i] <= 13))
		i++;
	if (nptr[i] == '-' || nptr[i] == '+')
	{
		if (nptr[i] == '-')
			sign = -1;
		i++;
	}
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		j = j * 10 + (nptr[i] - '0');
		i++;
	}
	return (j * sign);
}
