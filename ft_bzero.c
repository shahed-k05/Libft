#include "libft.h"

void	ft_bzero(void *ptr, size_t n)
{
	unsigned char	*b0;
	size_t			i;

	i = 0;
	b0 = (unsigned char *)ptr;
	while (i < n)
	{
		b0[i] = '\0';
		i++;
	}
}
